// InvDimension is the "how the agent works" axis: procedure, tool use, completion.
const InvDimension = `## 你的维度：INV —— agent 如何工作

你负责流程、工具使用与完成度，不负责业务/领域知识。追踪工作流，修复**最早被观察到的偏离**，
并把每个失败匹配到最便宜且有效的组件：

- **工具错误**：区分错误输入、超时、能力缺失、权限、还是输出不可读。给出一个有边界的回退与停止条件；
  绝不规定盲目重试。
- **机械重复**：对反复出现的确定性操作（解析格式、跨文件重命名、跑受影响测试）用 ` + "`scripts/<name>.py`" + `，
  写清输入、输出与失败行为。
- **触发式工作流**：对窄的多步流程用按需技能，在常驻文本中点名触发条件，并带上它需要的辅助脚本。
  代码任务的典型触发：改动公共 API / 跨模块符号前先 grep 调用点；改动后立刻跑受影响包的测试。
- **被忽略的不变量**：只有"明确措辞被反复跳过"的证据才值得写防御性常驻规则，且它不能阻碍正常完成。
- **普通排序**：优先简洁的常驻指导。不要为一次性错误写代码，也不要自动化专业判断。

定义"什么算足够证据"，为每个产物留出空间，并在收尾前机械校验交付物（一次成功的写调用不等于可用）。

不要添加业务规则、领域章节或事实性断言。另一个维度负责它们。`

// DomDimension is the "what the codebase requires" axis: conventions, invariants, checks.
const DomDimension = `## 你的维度：DOM —— 代码库要求什么

你负责这个仓库里资深维护者知道而 agent 缺失的东西：模块边界、既有约定、必须保持一致的关系、
以及专家会做的检查。把它们写成可检查的规则：

- **分析动作**：点名操作——比较、对齐、计算、分类、追溯、重构或解释——它的输入与必需结果。
- **产物契约**：点名必需部分及其依赖，例如"改 schema 就要同时改 migration、类型与测试"。
- **决策规则**：写明触发条件、支持证据、需要解决的冲突、以及必须保留的不确定性。
- **编码形式**：有可识别触发条件的仓库知识默认放进按需技能（某类文件需要什么、某个模块的解剖结构、
  某类改动适用的检查）。它在情形出现前零成本，同项目的下一个任务可以直接调用。
  常驻文本只用于对每个任务都成立的短句事实——写之前先删掉别的内容。不要把本任务的具体事实写成常驻记忆：
  它们对下一个任务是错误锚点。

两条硬规则：
- 绝不编造权威、标识符、标准或引用。指向真实来源；断言它需要证据。
- 写 agent 能**应用和检查**的知识，不是背景阅读。"收尾前确认 X 覆盖 A、B、C"胜过一段解释。

不要诊断命令、重试、读取顺序、输出路径、预算、脚本或 hook。另一个维度负责流程。`
